/**
 * The logotype as inline SVG.
 *
 * `height` sets the printed size; the width follows the lockup's own aspect
 * ratio so the mark never stretches.
 */
export function oryxLogoMark(height: string, className = 'of-logo-mark'): string {
  const paths = ORYX_LOGO_PATHS.map((p) => `<path fill="${p.fill}" d="${p.d}"/>`).join('');
  return `<svg class="${className}" viewBox="${ORYX_LOGO_VIEWBOX}" height="${height}" role="img" aria-label="ORYX">${paths}</svg>`;
}
