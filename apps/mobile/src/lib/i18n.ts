export function translate(locale: Locale, key: keyof typeof strings): string {
  const entry = strings[key];
  if (!entry) return String(key);
  return entry[locale];
}

export type TranslateKey = keyof typeof strings;

/** Locale-aware picker for a demo record's `nameEn`/`nameAr` pair. */
export function localized(locale: Locale, pair: { en: string; ar: string }): string {
  return locale === 'ar' ? pair.ar : pair.en;
}
