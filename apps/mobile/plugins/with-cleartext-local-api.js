const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * Permits cleartext HTTP to the local development API only.
 *
 * Android blocks plain HTTP by default from targetSdk 28 onward, so a release
 * build cannot reach `http://localhost:3001` (or the emulator host alias
 * `http://10.0.2.2:3001`) without an explicit exemption. The symptom is silent:
 * OkHttp throws `UnknownServiceException`, the app maps it to an offline error,
 * and every live rail renders empty with no log line.
 *
 * The exemption is deliberately narrow — it names the loopback hosts and the
 * emulator host alias a device uses during testing, and nothing else. A
 * production host must be HTTPS, so no public domain is listed here.
 *
 * `apps/mobile/android` is generated and git-ignored, so the policy is declared
 * here and applied by `expo prebuild` rather than hand-edited into the manifest.
 */

const LOCAL_HOSTS = ['localhost', '127.0.0.1', '10.0.2.2', '10.0.3.2'];

function networkSecurityConfigXml() {
  const domains = LOCAL_HOSTS.map(
    (host) => `    <domain includeSubdomains="false">${host}</domain>`,
  ).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by plugins/with-cleartext-local-api.js - do not edit by hand.
  Cleartext is allowed only for the local API hosts used during development.
  Every other destination stays HTTPS-only.
-->
<network-security-config>
  <domain-config cleartextTrafficPermitted="true">
${domains}
  </domain-config>
  <base-config cleartextTrafficPermitted="false" />
</network-security-config>
`;
}

/** Writes the network security config into the generated Android res/xml. */
const withNetworkSecurityConfigFile = (config) =>
  withDangerousMod(config, [
    'android',
    async (cfg) => {
      const xmlDir = path.join(
        cfg.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
        'xml',
      );
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(
        path.join(xmlDir, 'network_security_config.xml'),
        networkSecurityConfigXml(),
        'utf8',
      );
      return cfg;
    },
  ]);

/** Points the application at the config above. */
const withCleartextManifest = (config) =>
  withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    // Also set the boolean, so a device that ignores the config file still
    // allows the loopback hosts this build is meant to reach.
    app.$['android:usesCleartextTraffic'] = 'true';
    return cfg;
  });

module.exports = (config) =>
  withCleartextManifest(withNetworkSecurityConfigFile(config));
