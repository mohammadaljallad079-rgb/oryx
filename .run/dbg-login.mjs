import { chromium } from 'playwright';
const ADMIN = 'https://work-1-yumhfnmvqfdgaghd.prod-runtime.all-hands.dev';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport:{width:1440,height:900} })).newPage();
p.on('console', m => console.log('CONSOLE', m.type(), m.text().slice(0,200)));
p.on('pageerror', e => console.log('PAGEERR', String(e).slice(0,200)));
await p.goto(`${ADMIN}/login`, { waitUntil: 'networkidle', timeout: 90000 });
console.log('URL', p.url());
console.log('has email field:', await p.locator('[data-testid="login-email"]').count());
await p.screenshot({ path: '/tmp/dbg-login.png' });
await p.locator('[data-testid="login-email"]').fill('admin@oryx-auto.local');
await p.locator('[data-testid="login-password"]').fill('ChangeMe!Oryx2026');
await p.locator('form:has([data-testid="login-email"]) button[type="submit"]').first().click();
await p.waitForTimeout(8000);
console.log('after submit URL', p.url());
const body = (await p.evaluate(()=>document.body.innerText)).replace(/\s+/g,' ').slice(0,400);
console.log('BODY', body);
await p.screenshot({ path: '/tmp/dbg-after.png' });
await b.close();
