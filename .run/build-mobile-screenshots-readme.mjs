/**
 * Generates `docs/audit/exec07/marketplace-demo/README.md`, the index the owner
 * asked for: every screen, with a GitHub link that still works after the
 * OpenHands session ends.
 *
 * The screen list is read from `screenshots/manifest.json`, which the capture
 * script writes, so the index cannot drift from the images that exist.
 *
 * Run with: node .run/build-mobile-screenshots-readme.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const REPO = 'mohammadaljallad079-rgb/oryx';
const BRANCH = 'feature/execution-07-premium-web';
const DIR = 'docs/audit/exec07/marketplace-demo/screenshots';
const VIEW = `https://github.com/${REPO}/blob/${BRANCH}/${DIR}`;
const FULL = `https://raw.githubusercontent.com/${REPO}/${BRANCH}/${DIR}`;

const manifest = JSON.parse(readFileSync(`${DIR}/manifest.json`, 'utf8'));
const isMerchant = (x) => x.route.startsWith('/merchant');
const en = manifest.filter((x) => x.locale === 'en' && !isMerchant(x));
const ar = manifest.filter((x) => x.locale === 'ar' && !isMerchant(x));
const merchant = manifest.filter(isMerchant);

/** A row per screen: label, route, a browsable link and the raw image. */
const table = (items, prefix) =>
  [
    '| Screen | Route | View | Image |',
    '| --- | --- | --- | --- |',
    ...items.map(
      (x) =>
        `| ${x.label} | \`${x.route}\` | [view](${VIEW}/${prefix}/${x.name}.png) | ` +
        `[png](${FULL}/${prefix}/${x.name}.png) |`,
    ),
  ].join('\n');

const doc = `# ORYX Marketplace — screen gallery

Every screen of \`apps/mobile\`, captured from the running app. ${manifest.length}
images: ${en.length} customer screens in English, ${ar.length} in Arabic, and
${merchant.length} in the merchant shell.

- [Contact sheet](${VIEW}/contact-sheet.png) — all of them in one image
- [Browse the machine-readable manifest](${VIEW}/manifest.json)

All of them are the **light theme** — Execution 07 Phase E is the light-theme
correction, so that is the theme under review. The app's stored default is the
dark theme; the approved dark captures live one directory up, in
[\`../\`](https://github.com/${REPO}/tree/${BRANCH}/docs/audit/exec07/marketplace-demo),
one per screen beside its light counterpart.

## How these were taken

The web export of the same components the APK ships (\`expo export --platform
web\`), at 430×932 with a 2× device scale — a handset frame. The stored session
and the locale are seeded before the bundle runs, so the sweep navigates *inside*
the app.

That last detail matters: a full page reload drops the in-memory access token, so
driving the app by reloading a URL per screen produces a sign-in page or an error
for every route past the first. Navigating internally is what makes these
captures the real screens.

The APK is the native build of exactly these components; the imagery is bundled,
not remote, so the same screens render with the radio off.

## Customer — English (LTR)

${table(en, 'en')}

## Customer — Arabic (RTL)

${table(ar, 'ar')}

## Merchant shell

${table(merchant, 'merchant')}

---

Generated by \`node .run/build-mobile-screenshots-readme.mjs\`.
`;

writeFileSync('docs/audit/exec07/marketplace-demo/README.md', doc);
console.log(`wrote docs/audit/exec07/marketplace-demo/README.md — ${manifest.length} screens`);
